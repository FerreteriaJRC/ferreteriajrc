CREATE TABLE IF NOT EXISTS public.branch_transfer_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  origin_branch text NOT NULL,
  destination_branch text NOT NULL,
  seller_user_id bigint NOT NULL REFERENCES public.users(id),
  clients text[] NOT NULL CHECK (cardinality(clients) > 0),
  observations text NOT NULL DEFAULT '',
  created_by_user_id bigint NOT NULL REFERENCES public.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (lower(trim(origin_branch)) <> lower(trim(destination_branch)))
);

ALTER TABLE public.branch_transfer_requests ENABLE ROW LEVEL SECURITY;

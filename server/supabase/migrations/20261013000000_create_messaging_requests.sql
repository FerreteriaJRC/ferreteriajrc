CREATE TABLE IF NOT EXISTS public.messaging_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch text NOT NULL,
  request_date date NOT NULL,
  client text NOT NULL,
  seller_user_id bigint NOT NULL REFERENCES public.users(id),
  diligence_user_id bigint NOT NULL REFERENCES public.users(id),
  neighborhood text NOT NULL,
  observations text NOT NULL DEFAULT '',
  created_by_user_id bigint NOT NULL REFERENCES public.users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.messaging_requests ENABLE ROW LEVEL SECURITY;
